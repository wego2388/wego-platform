export function docMessage(lang: DocumentLanguage, key: DocumentMessageKey, params: Record<string, string | number> = {}): string {
  return (lang === "ar" ? ar : en)[key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : placeholder,
  );
}

export const DOCUMENT_MESSAGE_KEYS = Object.keys(en) as DocumentMessageKey[];
export const documentMessages = { en, ar } as const;

/** Shared dashboard labels the documents reuse (slots, methods) so wording never forks. */
export function sharedLabel(lang: DocumentLanguage, key: ErpMessageKey, params?: Record<string, string | number>): string {
  return erpMessage(lang, key, params);
}
